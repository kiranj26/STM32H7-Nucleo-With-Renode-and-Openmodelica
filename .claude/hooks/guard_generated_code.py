#!/usr/bin/env python3
"""PreToolUse guard: protect STM32CubeMX-generated firmware.

Policy (see CLAUDE.md, hard rule 1):
  fw/pN_*/Drivers/**, fw/pN_*/cmake/stm32cubemx/**  -> never edited (regenerated by CubeMX)
  fw/pN_*/*.ioc                                      -> GUI only, never hand-edited
  fw/pN_*/Core/**  existing files                    -> Edit allowed only inside USER CODE blocks
  fw/pN_*/Core/**  new files                         -> blocked; put new code in app/ or fw/common/
"""

from __future__ import annotations

import re
from pathlib import Path

from _hooklib import allow, block, edits_of, read_event, rel_path

FW_PROJECT = re.compile(r"^fw/p\d+_[^/]+/")
BEGIN = re.compile(r"USER CODE BEGIN")
END = re.compile(r"USER CODE END")


def inside_user_block(text: str, start: int, end: int) -> bool:
    """True if text[start:end] lies between a USER CODE BEGIN marker and the next END marker."""
    last_begin = max((m.end() for m in BEGIN.finditer(text, 0, start)), default=-1)
    last_end = max((m.end() for m in END.finditer(text, 0, start)), default=-1)
    if last_begin == -1 or last_begin < last_end:
        return False
    next_end = END.search(text, start)
    return next_end is not None and end <= next_end.start()


def check_core_edit(path: Path, rel: str, event: dict) -> None:
    tool = event.get("tool_name", "")
    if not path.exists():
        block(
            f"[guard] {rel}: don't create new files under CubeMX Core/. "
            "Put project code in fw/pN_*/app/ or shared code in fw/common/, "
            "and call it from a USER CODE block in main.c."
        )
    if tool == "Write":
        block(
            f"[guard] {rel} is CubeMX-generated; a full Write would clobber generated code. "
            "Use Edit confined to a /* USER CODE BEGIN */ ... /* USER CODE END */ block."
        )
    text = path.read_text(errors="replace")
    for old, new, replace_all in edits_of(event):
        if not old:
            continue
        if BEGIN.search(old) or END.search(old) or BEGIN.search(new) or END.search(new):
            block(f"[guard] {rel}: edits must not add, remove, or span USER CODE markers.")
        positions = [m.start() for m in re.finditer(re.escape(old), text)]
        if not positions:
            continue  # let the Edit tool report "string not found" itself
        if not replace_all:
            positions = positions[:1]
        for pos in positions:
            if not inside_user_block(text, pos, pos + len(old)):
                line = text.count("\n", 0, pos) + 1
                block(
                    f"[guard] {rel}:{line} is outside a USER CODE block and would be lost on "
                    "CubeMX regeneration. Move the change into a USER CODE block, into app/, "
                    "or change the .ioc in CubeMX and regenerate."
                )


def main() -> None:
    event = read_event()
    file_path = (event.get("tool_input", {}) or {}).get("file_path", "")
    rel = rel_path(file_path) if file_path else None
    if not rel or not FW_PROJECT.match(rel):
        allow()

    sub = FW_PROJECT.sub("", rel)
    if sub.startswith("Drivers/") or sub.startswith("cmake/stm32cubemx/"):
        block(f"[guard] {rel} is regenerated by CubeMX; never edit it. Change the .ioc instead.")
    if sub.endswith(".ioc"):
        block(
            f"[guard] {rel}: edit .ioc files in the STM32CubeMX GUI (macOS host), then regenerate. "
            "Describe the exact CubeMX settings to change instead."
        )
    if sub.startswith("Core/"):
        check_core_edit(Path(file_path), rel, event)
    allow()


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception:  # never break the session because of a hook bug
        allow()
